"""Production checks against a running deployment (used by CI after the Docker
image is built and started). Standard library only, so CI needs nothing extra.

    python .github/scripts/production_check.py http://127.0.0.1:8000 --health /health

Checks: smoke (every read endpoint), API contract (valid input accepted,
invalid input rejected, create -> read -> update -> delete), hostile input
(no server errors or leaked stack traces), and load (no errors, p95 within
budget). Endpoints and request bodies come from the app's OpenAPI schema.
Exits 1 if any check fails; writes a summary table for GitHub Actions.
Generated by Intent2Deploy AI.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor

TRACEBACK = re.compile(r"Traceback \(most recent call last\)|File \"[^\"]+\.py\", line \d+")
RESULTS: list[tuple[str, bool, str]] = []


def call(base: str, method: str, path: str, body: object = None, raw: bytes | None = None) -> tuple[int, str, float]:
    data = raw if raw is not None else (json.dumps(body).encode() if body is not None else None)
    req = urllib.request.Request(  # noqa: S310 - URL is the app under test
        base + path, data=data, method=method, headers={"Content-Type": "application/json"}
    )
    started = time.monotonic()
    try:
        with urllib.request.urlopen(req, timeout=10) as resp:  # noqa: S310 - URL is the app under test
            return resp.status, resp.read(20000).decode("utf-8", "replace"), (time.monotonic() - started) * 1000
    except urllib.error.HTTPError as exc:
        return exc.code, exc.read(20000).decode("utf-8", "replace"), (time.monotonic() - started) * 1000
    except (urllib.error.URLError, OSError) as exc:
        return 0, str(exc), (time.monotonic() - started) * 1000


def check(name: str, status: int, text: str, ok) -> bool:  # noqa: ANN001 - ok(status) -> bool
    passed = status != 0 and ok(status) and not TRACEBACK.search(text)
    detail = f"HTTP {status}" if status else f"no response ({text[:80]})"
    if TRACEBACK.search(text):
        detail += ", leaks a stack trace"
    RESULTS.append((name, passed, detail))
    return passed


def resolve(schema: dict, root: dict) -> dict:
    for _ in range(20):
        if not isinstance(schema, dict) or "$ref" not in schema:
            break
        node: object = root
        for part in schema["$ref"].lstrip("#/").split("/"):
            node = node.get(part, {}) if isinstance(node, dict) else {}
        schema = node if isinstance(node, dict) else {}
    return schema if isinstance(schema, dict) else {}


def sample(schema: dict, root: dict, name: str = "", depth: int = 0):  # noqa: ANN201 - any JSON value
    schema = resolve(schema, root)
    if depth > 6:
        return None
    if schema.get("default") is not None:
        return schema["default"]
    if schema.get("enum"):
        return schema["enum"][0]
    for key in ("anyOf", "oneOf"):
        if key in schema:
            options = [o for o in schema[key] if resolve(o, root).get("type") != "null"] or schema[key]
            return sample(options[0], root, name, depth + 1)
    kind = schema.get("type")
    if kind == "object" or "properties" in schema:
        return {k: sample(v, root, k, depth + 1) for k, v in (schema.get("properties") or {}).items()}
    if kind == "array":
        return [sample(schema.get("items") or {}, root, name, depth + 1)]
    if kind in ("integer", "number"):
        low = schema.get("minimum", schema.get("exclusiveMinimum", 0) + 1 if "exclusiveMinimum" in schema else 1)
        return int(low) if kind == "integer" else float(low)
    if kind == "boolean":
        return True
    fmt, lname = schema.get("format", ""), name.lower()
    formats = {"date": "2030-01-15", "date-time": "2030-01-15T10:00:00Z", "email": "qa.user@example.com",
               "uri": "https://example.com", "uuid": "123e4567-e89b-12d3-a456-426614174000"}
    if fmt in formats:
        return formats[fmt]
    candidates = ["qa.user@example.com"] if "email" in lname else []
    candidates += ["Str0ng-Passw0rd!"] if "password" in lname else []
    candidates += ["+15550100100", "9876543210"] if "phone" in lname else []
    value = (f"Sample {name}" if name else "Sample value").ljust(int(schema.get("minLength", 0)), "x")
    candidates.append(value[: int(schema["maxLength"])] if schema.get("maxLength") else value)
    if schema.get("pattern"):
        candidates += ["9876543210", "+15550100100", "Sample", "ABC123", "123456"]
        return next((c for c in candidates if re.search(schema["pattern"], c)), candidates[0])
    return candidates[0]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("base_url")
    parser.add_argument("--health", default="/health")
    parser.add_argument("--requests", type=int, default=300)
    parser.add_argument("--concurrency", type=int, default=20)
    parser.add_argument("--p95-ms", type=int, default=1000)
    parser.add_argument("--boot-timeout", type=int, default=60)
    args = parser.parse_args()
    base = args.base_url.rstrip("/")

    deadline = time.monotonic() + args.boot_timeout
    while call(base, "GET", args.health)[0] not in range(200, 400):
        if time.monotonic() > deadline:
            check(f"Boot: GET {args.health}", *call(base, "GET", args.health)[:2], lambda s: s < 400)
            return report()
        time.sleep(1)
    RESULTS.append((f"Boot: GET {args.health}", True, "healthy"))

    status, text, _ = call(base, "GET", "/openapi.json")
    spec = json.loads(text) if status == 200 else {}
    routes = [(m.upper(), p, op) for p, ops in (spec.get("paths") or {}).items() if p not in ("/docs", "/redoc")
              for m, op in ops.items() if isinstance(op, dict)]
    gets = [p for m, p, op in routes if m == "GET" and "{" not in p
            and not any(q.get("required") for q in op.get("parameters", []) if isinstance(q, dict))]

    # Smoke
    check("Smoke: GET /", *call(base, "GET", "/")[:2], lambda s: s < 500)
    for path in gets[:8]:
        check(f"Smoke: GET {path}", *call(base, "GET", path)[:2], lambda s: s < 500)

    # API contract + hostile input
    for method, path, op in routes:
        schema = (((op.get("requestBody") or {}).get("content") or {}).get("application/json") or {}).get("schema")
        if method not in ("POST", "PUT", "PATCH") or schema is None or "{" in path:
            continue
        body = sample(schema, spec)
        status, text, _ = call(base, method, path, body)
        check(f"API: {method} {path} with a valid body", status, text, lambda s: s < 500)
        if status in (200, 201):
            created = json.loads(text) if text.startswith("{") else {}
            item = f"{path}/{created.get('id')}" if "id" in created else ""
            if item and any(m == "GET" and re.fullmatch(re.escape(path) + r"/\{[^}/]+\}", p) for m, p, _ in routes):
                check(f"API: GET {path}/{{id}} returns it", *call(base, "GET", item)[:2], lambda s: s == 200)
                if any(m == "DELETE" and re.fullmatch(re.escape(path) + r"/\{[^}/]+\}", p) for m, p, _ in routes):
                    check(f"API: DELETE {path}/{{id}}", *call(base, "DELETE", item)[:2], lambda s: s < 300)
                    check(f"API: GET {path}/{{id}} after delete is 404",
                          *call(base, "GET", item)[:2], lambda s: s == 404)
        if resolve(schema, spec).get("required"):
            check(f"API: {method} {path} without required fields",
                  *call(base, method, path, {})[:2], lambda s: 400 <= s < 500)
        check(f"Hostile: {method} {path} malformed JSON",
              *call(base, method, path, raw=b"{bad")[:2], lambda s: 400 <= s < 500)
        check(f"Hostile: {method} {path} 1 MB payload",
              *call(base, method, path, {"name": "x" * 1_000_000})[:2], lambda s: s < 500)
        check(f"Hostile: {method} {path} injection strings",
              *call(base, method, path, {"name": "<script>alert(1)</script>' OR '1'='1"})[:2], lambda s: s < 500)
    check("Hostile: unknown route is 404", *call(base, "GET", "/__does_not_exist__")[:2], lambda s: s == 404)

    # Load
    targets = [args.health] + gets[:4]
    timings = []
    errors = []

    def one(i: int) -> None:
        status, _, ms = call(base, "GET", targets[i % len(targets)])
        timings.append(ms)
        if status == 0 or status >= 500:
            errors.append(status)

    with ThreadPoolExecutor(max_workers=args.concurrency) as pool:
        list(pool.map(one, range(args.requests)))
    timings.sort()
    p95 = timings[int(0.95 * (len(timings) - 1))]
    load = f"Load: {args.requests} requests, {args.concurrency} concurrent"
    RESULTS.append((load, not errors, f"{len(errors)} errors"))
    RESULTS.append((f"Load: p95 within {args.p95_ms} ms", p95 <= args.p95_ms, f"p95 {p95:.0f} ms"))
    check("Healthy after all checks", *call(base, "GET", args.health)[:2], lambda s: s < 400)
    return report()


def report() -> int:
    failed = [r for r in RESULTS if not r[1]]
    for name, passed, detail in RESULTS:
        print(f"{'PASS' if passed else 'FAIL'}  {name} — {detail}")
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a", encoding="utf-8") as fh:
            fh.write(f"### Production checks: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed\n\n")
            fh.write("| | Check | Result |\n|---|---|---|\n")
            fh.writelines(f"| {'✅' if p else '❌'} | {n} | {d} |\n" for n, p, d in RESULTS)
    print(f"\n{len(RESULTS) - len(failed)}/{len(RESULTS)} checks passed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
